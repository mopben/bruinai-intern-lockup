import { test, expect } from './support/fixtures';
import { openStage, chooseLibraryEntry } from './support/stage';

test('profit appears on selection, updates from prices and salaries, and playback is optional', async ({ page }) => {
  await openStage(page);
  const setupA = (await page.getByTestId('active-setup').getAttribute('data-value'))!;
  await page.getByTestId('step-orders').click();
  await chooseLibraryEntry(page, 'shift', '__create_shift__');
  await page.getByTestId('shift-hours').fill('1');
  const recipe = page.getByTestId('recipe-latte');
  await recipe.locator('summary').click();
  await recipe.getByLabel('Quantity in simulation').fill('3');
  await recipe.getByLabel('Selling price', { exact: true }).fill('10');
  await recipe.getByLabel('Ingredient cost', { exact: true }).fill('2');
  await page.getByTestId('step-results').click();
  await expect(page.getByTestId('compare-before-sales')).toHaveText('$30.00');
  await expect(page.getByTestId('compare-before').locator('.st-financial dt')).toHaveText(['Net profit', 'Sales revenue', 'Labor costs', 'Operating costs']);
  await expect(page.getByTestId('compare-before-profit')).toHaveText('-$43.50');
  await expect(page.getByTestId('compare-clock')).toHaveCount(0);
  await expect(page.getByTestId('compare-before-done')).toHaveCount(0);
  const scene = page.getByTestId('compare-before').locator('.scene');
  await expect(scene.locator('canvas')).toBeVisible();
  const sceneBounds = await scene.boundingBox();
  expect(sceneBounds!.height).toBeGreaterThan(page.viewportSize()!.height * .6);
  const profitBounds = await page.getByTestId('compare-before-profit').boundingBox();
  expect(profitBounds!.y).toBeGreaterThan(sceneBounds!.y + sceneBounds!.height);
  const profit = await page.getByTestId('compare-before-profit').innerText();
  await page.getByTestId('btn-play').click();
  await expect(page.getByTestId('compare-clock')).toBeVisible();
  await page.getByTestId('btn-skip').click();
  await expect(page.getByTestId('compare-before-done')).toHaveCount(0);
  await expect(page.getByTestId('compare-before-profit')).toHaveText(profit);
  await page.getByTestId('step-build').click();
  await chooseLibraryEntry(page, 'setup', '__create_setup__');
  const setupB = (await page.getByTestId('active-setup').getAttribute('data-value'))!;
  await page.getByTestId('btn-workers').click();
  const salary = page.locator('[data-testid^="worker-salary-"]').first();
  await salary.fill('28');
  await salary.blur();
  await page.getByTestId('btn-close-workers').click();
  await page.getByTestId('step-results').click();
  await page.getByTestId('scenario-0-setup').selectOption(setupA);
  await page.getByTestId('scenario-1-setup').selectOption(setupB);
  await expect(page.getByTestId('compare-before-profit')).toHaveText('-$43.50');
  await expect(page.getByTestId('compare-after-profit')).toHaveText('-$53.50');
  await expect(page.getByTestId('compare-clock')).toHaveCount(0);
  await page.reload();
  await expect(page.getByTestId('compare-before-profit')).toHaveText('-$43.50');
  await expect(page.getByTestId('compare-after-profit')).toHaveText('-$53.50');
  await page.getByTestId('step-orders').click();
  await expect(page.getByTestId('shift-hours')).toHaveValue('1');
  await page.getByTestId('recipe-latte').locator('summary').click();
  await expect(page.getByTestId('recipe-latte').getByLabel('Selling price', { exact: true })).toHaveValue('10');
});
